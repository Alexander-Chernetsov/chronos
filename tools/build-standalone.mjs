import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const app = path.join(repo, "chronos-2.0");
const sourcePath = path.join(app, "chronos.html");
const licensePath = path.join(repo, "LICENSE");
const inputs = [sourcePath, fileURLToPath(import.meta.url), licensePath];
const demo = process.argv[2] === "--demo";
const target = process.argv[demo ? 3 : 2];
const outputPath = target
  ? path.resolve(process.cwd(), target)
  : path.join(repo, "output", demo ? "site/index.html" : "chronos-2.0-standalone.html");

function readLocal(source, closingTag) {
  if (/^(?:[a-z]+:|[/\\])/i.test(source)) {
    throw new Error(`Only relative Chronos assets can be embedded: ${source}`);
  }
  const assetPath = path.resolve(app, source);
  const relativePath = path.relative(app, assetPath);
  if (!relativePath || relativePath.startsWith("..") || path.isAbsolute(relativePath)) {
    throw new Error(`Asset escapes the Chronos directory: ${source}`);
  }
  const content = fs.readFileSync(assetPath, "utf8");
  inputs.push(assetPath);
  if (new RegExp(`</${closingTag}`, "i").test(content)) {
    throw new Error(`Unsafe </${closingTag} sequence in ${source}`);
  }
  return content;
}

let html = fs.readFileSync(sourcePath, "utf8");
html = html.replace(
  /<link\s+rel="stylesheet"\s+href="([^"]+)"\s*\/>/g,
  (_, source) =>
    `<style data-source="${source}">\n${readLocal(source, "style")}\n</style>`,
);

html = html.replace(
  /<script\s+src="([^"]+)"\s*><\/script>/g,
  (_, source) =>
    `<script data-source="${source}">\n${readLocal(source, "script")}\n</script>`,
);

if (demo) {
  const packs = {};
  for (const [kind, suffix] of [["themes", ".css"], ["locales", ".locale.js"]]) {
    packs[kind] = fs.readdirSync(path.join(app, kind)).filter(name => name.endsWith(suffix)).sort()
      .map(name => {
        const file = path.join(app, kind, name);
        inputs.push(file);
        return {name, source: fs.readFileSync(file, "utf8")};
      });
  }
  const readDemo = name => {
    const file = path.join(repo, "demo", name);
    inputs.push(file);
    return fs.readFileSync(file, "utf8");
  };
  const safePacks = JSON.stringify(packs).replaceAll("<", "\\u003c");
  if (!html.includes('<script data-source="scripts/chronos.core.js">') ||
      !html.includes('<script data-source="scripts/chronos.js">')) {
    throw new Error("Demo initialization anchors are missing");
  }
  html = html.replace('<script data-source="scripts/chronos.core.js">',
    `<script>globalThis.CHRONOS_DEMO = true; globalThis.CHRONOS_DEMO_PACKS = ${safePacks};</script>\n<script data-source="scripts/chronos.core.js">`);
  html = html.replace('<script data-source="scripts/chronos.js">',
    `<script data-source="demo/bootstrap.js">\n${readDemo("bootstrap.js")}\n</script>\n<script data-source="scripts/chronos.js">`);
  html = html.replace('</head>', `<style data-source="demo/demo.css">\n${readDemo("demo.css")}\n</style>\n</head>`);
  html = html.replace('<body>', `<body>\n<nav class="demo-toolbar" aria-label="Demo" id="demoToolbar">
    <span id="demoNotice">Demo · example tasks, stored in this browser</span>
    <a id="demoDownload" href="https://github.com/Alexander-Chernetsov/chronos/releases/latest/download/chronos.zip">Download</a>
    <a id="demoSource" href="https://github.com/Alexander-Chernetsov/chronos">Source</a>
    <button id="demoReset" type="button">Reset demo</button>
  </nav>`);
}

const warning = [
  "<!--",
  "  Generated by tools/build-standalone.mjs.",
  "  Do not edit this file; change chronos-2.0 sources and rebuild.",
  "",
  fs.readFileSync(licensePath, "utf8").trim().replaceAll("-->", "--&gt;"),
  "-->",
].join("\n");
html = html.replace(/(<!doctype html>)/i, `$1\n${warning}`);

// Metadata is outside canonical assets; exports without Git simply omit it.
const git = (...args) => spawnSync("git", args, {cwd: repo, encoding: "utf8", windowsHide: true});
const head = git("rev-parse", "HEAD");
const sha = head.stdout?.trim();
if (head.status === 0 && /^[a-f0-9]{40}$/.test(sha)) {
  const paths = [...new Set(inputs.map(input => path.relative(repo, input).replaceAll("\\", "/")))];
  const tracked = git("ls-files", "-z", "--", ...paths);
  const diff = git("diff", "--quiet", "HEAD", "--", ...paths);
  if (tracked.status !== 0 || ![0, 1].includes(diff.status)) {
    throw new Error("Cannot determine standalone build input status");
  }
  const trackedPaths = new Set(tracked.stdout.split("\0"));
  const modified = diff.status === 1 || paths.some(input => !trackedPaths.has(input));
  html = html.replace(/<head>/i, `<head>\n    <meta name="chronos-build" content="${sha}${modified ? "+modified" : ""}" />`);
}

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, html, "utf8");
console.log(path.relative(repo, outputPath) || outputPath);
