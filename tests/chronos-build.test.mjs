import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";

const repo = path.resolve(import.meta.dirname, "..");
const app = path.join(repo, "chronos-2.0");
const sourceHtml = fs.readFileSync(path.join(app, "chronos.html"), "utf8");
const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), "chronos-standalone-"));

test.after(() => {
  assert.ok(tempDir.startsWith(path.resolve(os.tmpdir()) + path.sep));
  fs.rmSync(tempDir, { recursive: true, force: true });
});

function build(fileName) {
  const outputPath = path.join(tempDir, fileName);
  const result = spawnSync(
    process.execPath,
    [path.join(repo, "tools", "build-standalone.mjs"), outputPath],
    { cwd: repo, encoding: "utf8" },
  );
  assert.equal(result.status, 0, result.stderr);
  return fs.readFileSync(outputPath, "utf8");
}

const standalone = build("chronos-a.html");
const repeatedBuild = build("chronos-b.html");
assert.equal(standalone, repeatedBuild, "standalone build must be deterministic");
assert.match(standalone, /Generated by tools\/build-standalone\.mjs/);
assert.ok(standalone.includes(fs.readFileSync(path.join(repo, "LICENSE"), "utf8").trim()),
  "a standalone download must carry its MIT notice");
assert.match(
  standalone,
  /<link id="visualThemeStylesheet" rel="stylesheet" \/>/,
  "runtime-selected theme link must remain available",
);

const styleSources = [
  ...sourceHtml.matchAll(/<link\s+rel="stylesheet"\s+href="([^"]+)"\s*\/>/g),
].map((match) => match[1]);
const scriptSources = [
  ...sourceHtml.matchAll(/<script\s+src="([^"]+)"\s*><\/script>/g),
].map((match) => match[1]);
assert.ok(styleSources.length > 0 && scriptSources.length > 0);

for (const source of styleSources) {
  assert.doesNotMatch(standalone, new RegExp(`href="${source}"`));
  const content = fs.readFileSync(path.join(app, source), "utf8");
  assert.ok(
    standalone.includes(`<style data-source="${source}">\n${content}\n</style>`),
    `stylesheet was not embedded exactly: ${source}`,
  );
}
for (const source of scriptSources) {
  assert.doesNotMatch(standalone, new RegExp(`src="${source}"`));
  const content = fs.readFileSync(path.join(app, source), "utf8");
  assert.ok(
    standalone.includes(`<script data-source="${source}">\n${content}\n</script>`),
    `script was not embedded exactly: ${source}`,
  );
  assert.doesNotThrow(() => new Function(content), `embedded script must parse: ${source}`);
}

const embeddedSources = [
  ...standalone.matchAll(/<(?:style|script) data-source="([^"]+)">/g),
].map((match) => match[1]);
assert.deepEqual(embeddedSources, [...styleSources, ...scriptSources]);

test("build SHA describes only actual inputs, with no invented SHA in exports", () => {
  const fixture = path.join(tempDir, "fixture");
  const inputs = ["chronos-2.0/chronos.html", "tools/build-standalone.mjs", "LICENSE",
    ...[...styleSources, ...scriptSources].map(source => `chronos-2.0/${source}`)];
  for (const input of inputs) {
    const target = path.join(fixture, input);
    fs.mkdirSync(path.dirname(target), {recursive: true});
    fs.copyFileSync(path.join(repo, input), target);
  }
  const run = (command, args) => {
    const result = spawnSync(command, args, {cwd: fixture, encoding: "utf8"});
    assert.equal(result.status, 0, result.stderr);
    return result.stdout.trim();
  };
  const buildMeta = () => {
    run(process.execPath, ["tools/build-standalone.mjs", "candidate.html"]);
    const html = fs.readFileSync(path.join(fixture, "candidate.html"), "utf8");
    const metas = [...html.matchAll(/<meta name="chronos-build" content="([^"]+)" \/>/g)];
    assert.ok(metas.length <= 1);
    return metas[0]?.[1];
  };
  assert.equal(buildMeta(), undefined, "source export without Git has no fake build");
  run("git", ["init", "-q"]);
  run("git", ["config", "user.name", "Chronos build test"]);
  run("git", ["config", "user.email", "build-test@example.invalid"]);
  run("git", ["config", "core.autocrlf", "false"]);
  run("git", ["config", "core.hooksPath", path.join(fixture, "no-hooks")]);
  run("git", ["add", "--", ...inputs]);
  run("git", ["-c", "commit.gpgSign=false", "commit", "-qm", "Fixture"]);
  const sha = run("git", ["rev-parse", "HEAD"]);
  assert.equal(buildMeta(), sha);
  const asset = path.join(fixture, "chronos-2.0/styles/chronos.base.css");
  const original = fs.readFileSync(asset, "utf8");
  fs.appendFileSync(asset, "\n/* build test */\n");
  assert.equal(buildMeta(), `${sha}+modified`, "unstaged input edits mark the build");
  run("git", ["add", "chronos-2.0/styles/chronos.base.css"]);
  assert.equal(buildMeta(), `${sha}+modified`, "staged input edits mark the build");
  fs.writeFileSync(asset, original);
  assert.equal(buildMeta(), sha, "metadata follows actual input bytes despite an intermediate index");
  run("git", ["add", "chronos-2.0/styles/chronos.base.css"]);
  run("git", ["rm", "--cached", "chronos-2.0/styles/chronos.base.css"]);
  assert.equal(buildMeta(), `${sha}+modified`, "untracked input marks the build");
  run("git", ["add", "chronos-2.0/styles/chronos.base.css"]);
  fs.writeFileSync(path.join(fixture, "debug.log"), "unrelated\n");
  assert.equal(buildMeta(), sha, "unrelated files and generated output do not mark the build");
  const license = path.join(fixture, "LICENSE");
  fs.appendFileSync(license, "\nAdditional build-test notice\n");
  assert.equal(buildMeta(), `${sha}+modified`, "the distributed license is a build input");
});
